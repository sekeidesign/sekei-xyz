/**
 * One icon per post kind, in an outline and a solid pose. Both draw with
 * currentColor so the caller controls the tint.
 */
import type { ComponentType } from "react";

export interface KindIconProps {
	size?: number;
	className?: string;
	/** Solid pose. Outline is the default. */
	filled?: boolean;
}

function wrap(
	name: string,
	fillPaths: string[],
	strokePaths: string[],
): ComponentType<KindIconProps> {
	const Icon = ({ size = 16, className, filled = false }: KindIconProps) => (
		<svg
			width={size}
			height={size}
			viewBox="0 0 16 16"
			fill="none"
			xmlns="http://www.w3.org/2000/svg"
			className={className}
			style={{ flexShrink: 0 }}
			aria-hidden="true"
			focusable="false"
		>
			{filled
				? fillPaths.map((d) => (
						<path
							key={d.slice(0, 24)}
							fillRule="evenodd"
							clipRule="evenodd"
							d={d}
							fill="currentColor"
						/>
					))
				: strokePaths.map((d) => (
						<path
							key={d.slice(0, 24)}
							d={d}
							fill="none"
							stroke="currentColor"
							strokeWidth={4 / 3}
							strokeLinecap="round"
							strokeLinejoin="round"
						/>
					))}
		</svg>
	);
	Icon.displayName = `${name}KindIcon`;
	return Icon;
}

